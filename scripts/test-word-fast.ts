import assert from "node:assert/strict";
import {zipSync,unzipSync,strToU8,strFromU8} from "fflate";
import {buildWord,editWord,readEditableWord} from "../lib/word-fast";
import {fastWordMode} from "../lib/chat-task-policy";
import {validateOutput} from "../lib/chat-documents";
const bytes=buildWord({filename:"test.docx",title:"Bản mô tả công việc",summary:"",blocks:[{type:"paragraph",text:"Giữ mã SOURCE-742 và số 120000.",rows:[]},{type:"table",text:"",rows:[["Vai trò","Mức lương"],["Backend Developer","Thỏa thuận"]]}]});
validateOutput(bytes,"test.docx");
const archive=unzipSync(bytes);
archive["word/document.xml"]=strToU8(strFromU8(archive["word/document.xml"]).replace("Backend Developer","Backend</w:t></w:r><w:r><w:t> Developer"));
const source=readEditableWord(zipSync(archive));
const edited=unzipSync(editWord(source,{summary:"Updated",replacements:[{from:"Backend Developer",to:"Full-stack Developer",occurrences:1}]}));
assert.match(strFromU8(edited["word/document.xml"]),/Full-stack Developer/);
assert.match(strFromU8(edited["word/document.xml"]),/SOURCE-742/);
for(const name of Object.keys(archive))if(name!=="word/document.xml")assert.deepEqual(edited[name],archive[name],`Preserve ${name}`);
assert.throws(()=>editWord(source,{summary:"",replacements:[{from:"missing",to:"x",occurrences:1}]}),/occurrence mismatch/);
const atStart=readEditableWord(buildWord({filename:"a.docx",title:"Alpha",summary:"",blocks:[{type:"paragraph",text:"Alpha Alpha",rows:[]}]}));
const changed=readEditableWord(editWord(atStart,{summary:"",replacements:[{from:"Alpha",to:"Beta",occurrences:3}]}));
assert.equal(changed.text,"Beta\nBeta Beta");
assert.equal(fastWordMode("Tạo JD Developer và gửi file Word",[],false,false),"create");
assert.equal(fastWordMode("Đổi Backend thành Frontend trong file Word",[{name:"source.docx"}],false,false),"edit");
assert.equal(fastWordMode("Đổi Backend thành Frontend trong file này",[{name:"source.docx"}],false,false),"edit");
assert.equal(fastWordMode("Chuyển PDF sang Word",[{name:"source.pdf"}],false,false),null);
assert.equal(fastWordMode("Tạo Word và PowerPoint",[],false,false),null);
console.log("PASS: valid Word generation, split-run exact replacements, unchanged styles/footer/relationships, occurrence checks and routing.");
